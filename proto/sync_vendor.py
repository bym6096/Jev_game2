"""Make proto/ self-contained for Vercel (Root Directory = proto): copy the few repo modules it needs into proto/vendor and generate proto/data/*.json.
Run after changing sim/orbsim.py, measurements/orb_axes/axes*.py, toys/card-forge/forge.py or the starter orbs:   python proto/sync_vendor.py
`python proto/sync_vendor.py --check` fails if the committed copies differ from what would be generated."""
import os, re, sys, json, random, shutil
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, ".."); VEN = os.path.join(HERE, "vendor"); DATA = os.path.join(HERE, "data")
CHECK = "--check" in sys.argv; bad = []
def write(path, text):
    if CHECK:
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text: bad.append(os.path.relpath(path, HERE))
    else:
        os.makedirs(os.path.dirname(path), exist_ok=True); open(path, "w", encoding="utf-8", newline="\n").write(text)
for f in ("axes", "axes_v1", "axes_v2", "axes_v3", "axes_v4"):
    t = open(os.path.join(ROOT, "measurements", "orb_axes", f + ".py"), encoding="utf-8").read()
    t = re.sub(r'^sys\.path\.insert\(0, "/home/user/Jev_game2/measurements/orb_axes"\)\n', "", t, flags=re.M)
    write(os.path.join(VEN, f + ".py"), "# VENDORED copy of measurements/orb_axes/%s.py (generated by proto/sync_vendor.py)\n%s" % (f, t))
write(os.path.join(VEN, "forge.py"), "# VENDORED copy of toys/card-forge/forge.py (generated by proto/sync_vendor.py)\n" + open(os.path.join(ROOT, "toys", "card-forge", "forge.py"), encoding="utf-8").read())
src = open(os.path.join(ROOT, "sim", "orbsim.py"), encoding="utf-8").read(); head = src[:src.index("# ---- the game")]
head = re.sub(r'^""".*?"""', '"""GENERATED by proto/sync_vendor.py from sim/orbsim.py: orb construction only (no measured data files). Orbs come from live Jev answers via make_orb(..., extra=...)."""', head, count=1, flags=re.S)
old = 'V3, V2, V4, PROD = _load("out_v3.jsonl"), _load("out_v2.jsonl"), _load("out_v4.jsonl"), _load("out_prod.jsonl")'
assert old in head; head = head.replace(old, "V3, V2, V4, PROD = {}, {}, {}, {}")
write(os.path.join(VEN, "orbmake.py"), head)
if not CHECK or True:
    sys.path.insert(0, VEN); sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(ROOT, "sim"))
    import orbsim as SIM                       # measured data (dev only)
    import orbs                                # proto module (uses the vendored orbmake)
    starters = [orbs.to_dict(SIM.make_orb(n, cost_model=orbs.CM, gold_mult=orbs.GM)) for n in orbs.STARTER]
    write(os.path.join(DATA, "starter_orbs.json"), json.dumps(starters, ensure_ascii=False, indent=1))
    t = open(os.path.join(ROOT, "toys", "card-forge", "template.html"), encoding="utf-8").read()
    def lst(var):
        m = re.search(r"const " + var + r' = \((.*?)\)\.split\("\|"\)', t, re.S); return "".join(re.findall(r'"([^"]*)"', m.group(1))).split("|")
    fr = [["pre", x, True] for x in lst("PRE")] + [["suf", x, True] for x in lst("SUF_SP")] + [["suf", x, False] for x in lst("SUF_ATT")]
    write(os.path.join(DATA, "fragments.json"), json.dumps(fr, ensure_ascii=False))
if CHECK:
    print("차이 없음" if not bad else "차이 있음: " + ", ".join(bad)); sys.exit(1 if bad else 0)
print("동기화 완료")
