# 시작 주머니(범주별). 나머지는 보상에서 얻는다.
START = {"ref": 26, "adj": 18, "pred": 18, "mod": 10, "pol": 6, "int": 6}


# ---- 한국어 활용 ----
def dec(ch):
    c = ord(ch) - 0xAC00
    return c // 588, (c % 588) // 28, c % 28


def comp(cho, jung, jong=0):
    return chr(0xAC00 + cho * 588 + jung * 28 + jong)


BRIGHT = {0, 2, 8, 9, 12}            # ㅏ ㅑ ㅗ ㅘ ㅛ
J_RIEUL = 8


def conj(word):
    """기본형 → (어간, 해체, ㄹ형, 감탄형)"""
    irr = ""
    if "/" in word:
        word, irr = word.split("/")
    stem = word[:-1]
    pre, last = stem[:-1], stem[-1]
    cho, jung, jong = dec(last)
    if last == "하":
        return stem, pre + "해", pre + "할", stem + "네"
    if irr == "ㅂ":   # 무섭 → 무서워, 무서울
        base = pre + comp(cho, jung)
        return stem, base + "워", base + "울", stem + "네"
    if irr == "ㄷ":   # 듣 → 들어, 들을
        base = pre + comp(cho, jung, J_RIEUL)
        return stem, base + "어", base + "을", stem + "네"
    if last == "르" and pre:   # 부르 → 불러, 흐르 → 흘러, 마르 → 말라
        pc, pj, _ = dec(pre[-1])
        p2 = pre[:-1] + comp(pc, pj, J_RIEUL)
        return stem, p2 + ("라" if pj in BRIGHT else "러"), pre + "를", stem + "네"
    if jong == J_RIEUL:        # ㄹ 탈락: 날 → 날아, 날, 나네
        h = stem + ("아" if jung in BRIGHT else "어")
        return stem, h, stem, pre + comp(cho, jung) + "네"
    if jong:                   # 받침: 먹 → 먹어, 먹을
        return stem, stem + ("아" if jung in BRIGHT else "어"), stem + "을", stem + "네"
    # 받침 없음: 모음 축약
    l = pre + comp(cho, jung, J_RIEUL)
    if jung == 18:   # ㅡ: 아프 → 아파, 쓰 → 써
        prev_bright = bool(pre) and dec(pre[-1])[1] in BRIGHT
        h = pre + comp(cho, 0 if prev_bright else 4)
    elif jung == 8:  h = pre + comp(cho, 9)    # ㅗ → ㅘ (보 → 봐)
    elif jung == 13: h = pre + comp(cho, 14)   # ㅜ → ㅝ (주 → 줘)
    elif jung == 20: h = pre + comp(cho, 6)    # ㅣ → ㅕ (지 → 져)
    elif jung == 11: h = pre + comp(cho, 10)   # ㅚ → ㅙ (되 → 돼)
    elif jung in (0, 4, 1, 5): h = stem        # ㅏ ㅓ ㅐ ㅔ: 가 → 가
    else: h = stem + "어"
    return stem, h, l, stem + "네"


def words(s):
    for w in s.split(","):
        w = w.strip()
        if w:
            yield w.rstrip("!"), w.endswith("!")


def build():
    tiles, seen = [], set()

    def add(t):
        if t["id"] in seen:
            print("중복 건너뜀:", t["id"], file=sys.stderr)
            return
        seen.add(t["id"])
        tiles.append(t)

    def tid(cat, w):
        return f"{cat}_{w.replace(' ', '_').replace('/', '')}"

    for cat, table in (("ref", REF), ("adj", ADJ)):
        for dom, s in table.items():
            for w, rare in words(s):
                add({"id": tid(cat, w), "cat": cat, "ko": w, "dom": dom, **({"rare": 1} if rare else {})})
    for dom, s in PRED.items():
        for w, rare in words(s):
            st, h, l, ne = conj(w)
            ko = w.split("/")[0]
            t = {"id": tid("pred", ko), "cat": "pred", "ko": ko, "st": st, "h": h, "l": l, "dom": dom}
            if ne != st + "네":
                t["ne"] = ne
            if rare:
                t["rare"] = 1
            add(t)
    for cat, s in (("mod", MOD), ("pol", POL), ("int", INT)):
        for w, rare in words(s):
            add({"id": tid(cat, w), "cat": cat, "ko": w, **({"rare": 1} if rare else {})})
    return tiles


def pick_start(tiles, rng):
    """범주별로, 감각 영역을 고루 섞어 흔한 조각에서 고른다."""
    start = {}
    for cat, n in START.items():
        pool = [t for t in tiles if t["cat"] == cat and not t.get("rare")]
        rng.shuffle(pool)
        by = {}
        for t in pool:
            by.setdefault(t.get("dom", ""), []).append(t["id"])
        out = []
        while len(out) < n and any(by.values()):
            for d in list(by):
                if by[d] and len(out) < n:
                    out.append(by[d].pop())
        start[cat] = out
    return start


